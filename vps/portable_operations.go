package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// Portable state belongs to the invoking user, independently of the unpacked
// release. No root, systemd, Docker daemon or provider-specific path is needed.
func portableCommand(args []string, out io.Writer) error {
	if len(args) == 0 || !oneOf(args[0], "init", "run") {
		return errors.New("usage: portable init|run --directory ABSOLUTE_STATE_DIRECTORY [--public-origin HTTPS_ORIGIN]")
	}
	f := flag.NewFlagSet("portable", flag.ContinueOnError)
	f.SetOutput(io.Discard)
	directory := f.String("directory", "", "persistent private state directory")
	origin := f.String("public-origin", "", "HTTPS ingress origin for a new deployment")
	listen := f.String("listen", "127.0.0.1:8787", "numeric listener for a new deployment")
	backup := f.String("backup-destination", "", "explicit private backup destination for run")
	if f.Parse(args[1:]) != nil || f.NArg() != 0 || !filepath.IsAbs(*directory) || filepath.Clean(*directory) != *directory || strings.ContainsAny(*directory, "\r\n\x00\"\\") {
		return errors.New("portable operations require an absolute private state directory and valid options")
	}
	env := filepath.Join(*directory, "config", "modelatlas.env")
	if args[0] == "run" {
		if *origin != "" || *listen != "127.0.0.1:8787" {
			return errors.New("configure an existing deployment in its private environment file")
		}
		config, err := serveConfig([]string{"--env-file", env, "--backup-destination", *backup}, os.Getenv)
		if err != nil {
			return err
		}
		return runConfiguredApplication(config)
	}
	if *backup != "" {
		return errors.New("select the backup destination on portable run or in the private environment")
	}
	return initializePortable(*directory, env, *origin, *listen, out)
}

func initializePortable(directory, env, origin, listen string, out io.Writer) error {
	db := filepath.Join(directory, "data", "atlas.sqlite")
	gate := filepath.Join(directory, "data", ".update-pending")
	if info, err := os.Lstat(env); err == nil {
		if !info.Mode().IsRegular() {
			return errors.New("portable environment must be a private regular file")
		}
		config, e := serveConfig([]string{"--env-file", env}, func(string) string { return "" })
		if e != nil {
			return e
		}
		if config.db != db || (origin != "" && config.publicOrigin != origin) || (listen != "127.0.0.1:8787" && config.addr != listen) {
			return errors.New("existing deployment settings differ; keeping its database and keys")
		}
		_, e = fmt.Fprintln(out, "Existing private deployment retained. Use portable run with the same directory.")
		return e
	} else if !os.IsNotExist(err) {
		return errors.New("cannot inspect portable environment")
	}
	if entries, err := os.ReadDir(filepath.Join(directory, "data")); err == nil && len(entries) != 0 {
		return errors.New("existing data has no environment file; recover the original master key before continuing")
	} else if err != nil && !os.IsNotExist(err) {
		return errors.New("cannot inspect portable data directory")
	}
	for _, path := range []string{directory, filepath.Join(directory, "config"), filepath.Join(directory, "data"), filepath.Join(directory, "backups")} {
		if err := os.Mkdir(path, 0700); err != nil && !os.IsExist(err) {
			return errors.New("cannot create portable state directories; create the parent directory first")
		}
		info, err := os.Lstat(path)
		if err != nil || !info.IsDir() || info.Mode().Perm()&0077 != 0 {
			return errors.New("portable state directories must be private directories (chmod 700), without symbolic links")
		}
	}
	// Serialize first initialization, including concurrent invocations. A second
	// caller cannot replace credentials generated by the first one.
	lock, err := acquireDatabaseLock(filepath.Join(directory, ".initialize"))
	if err != nil {
		return errors.New("another portable initialization is in progress")
	}
	defer lock.Close()
	if _, err = os.Lstat(env); !os.IsNotExist(err) {
		return errors.New("environment appeared during initialization; keeping its existing keys")
	}
	temporary, err := os.MkdirTemp(filepath.Join(directory, "config"), ".initialize-")
	if err != nil {
		return errors.New("cannot prepare private environment")
	}
	defer os.RemoveAll(temporary)
	prepared := filepath.Join(temporary, "modelatlas.env")
	if err = initializeEnvironment(prepared, db, gate); err != nil {
		return err
	}
	raw, err := os.ReadFile(prepared)
	if err != nil {
		return errors.New("cannot read prepared private environment")
	}
	// The generated loopback default is replaced before publication; validation
	// occurs before any live environment file or database is created.
	raw = []byte(strings.Replace(string(raw), "MODELATLAS_LISTEN=127.0.0.1:8787\n", "MODELATLAS_LISTEN="+strconv.Quote(listen)+"\n", 1))
	if origin != "" {
		raw = append(raw, []byte("MODELATLAS_DEPLOYMENT=platform\nMODELATLAS_PUBLIC_ORIGIN="+strconv.Quote(origin)+"\n")...)
	}
	if err = os.WriteFile(prepared, raw, 0600); err != nil {
		return errors.New("cannot prepare private deployment settings")
	}
	if _, err = serveConfig([]string{"--env-file", prepared}, func(string) string { return "" }); err != nil {
		return err
	}
	if err = writeExclusive(env, raw, 0600); err != nil {
		return errors.New("cannot publish environment; existing settings were not replaced")
	}
	_, err = fmt.Fprintln(out, "Private deployment initialized. Back up its master key separately, then use portable run with the same directory.")
	return err
}
